# DP over time points: lane state; move cap = 1 lane per half beat
best = {2: (0, None)}  # lane -> (moves, path)
prev_t = None; paths = {2: []}
cost = {2: 0}
for t in times:
    here = [c for tt, c in ev if tt == t]
    def ok(l):
        for c in here:
            if c[0] == 'O' and str(l) in c[1:]: return False
            if c[0] == 'E' and abs(int(c[1]) - l) > 1: return False
            if c == 'F' and l not in (1,2,3): return False
        return True
    cap = 99 if prev_t is None else int((t - prev_t) / 0.5 + 1e-9)
    nc, np_ = {}, {}
    for l in range(5):
        if not ok(l): continue
        for pl, pc in cost.items():
            if abs(pl - l) <= cap:
                c = pc + abs(pl - l) + (0.01 * abs(l - 2))
                if l not in nc or c < nc[l]:
                    nc[l] = c; np_[l] = paths[pl] + [(t, l)]
    if not nc:
        print('IMPOSSIBLE at beat', t, here, 'from', cost); raise SystemExit(1)
    cost, paths = nc, np_; prev_t = t
